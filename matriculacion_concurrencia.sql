/*
   Gestión de concurrencia y consistencia
   Motor objetivo: PostgreSQL 14+
   Ejecución recomendada: psql -v ON_ERROR_STOP=1 -f matriculacion_concurrencia.sql
*/

DROP TABLE IF EXISTS registros_matricula;
DROP TABLE IF EXISTS asignaturas;
DROP TABLE IF EXISTS estudiantes;

CREATE TABLE estudiantes (
    estudiante_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    cedula VARCHAR(20) NOT NULL UNIQUE,
    facultad VARCHAR(120) NOT NULL
);

CREATE TABLE asignaturas (
    asignatura_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_materia VARCHAR(120) NOT NULL UNIQUE,
    docente VARCHAR(120) NOT NULL,
    cupos_disponibles INTEGER NOT NULL CHECK (cupos_disponibles >= 0)
);

CREATE TABLE registros_matricula (
    registro_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id INTEGER NOT NULL REFERENCES estudiantes(estudiante_id),
    asignatura_id INTEGER NOT NULL REFERENCES asignaturas(asignatura_id),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(10) NOT NULL CHECK (estado IN ('CONFIRMADA', 'PENDIENTE')),
    CONSTRAINT estudiante_asignatura_unica UNIQUE (estudiante_id, asignatura_id)
);

