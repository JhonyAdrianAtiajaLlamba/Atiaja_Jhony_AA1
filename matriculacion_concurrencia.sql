/* Transacción A: matrícula confirmada y descuento atómico de cupo. */
BEGIN;
INSERT INTO registros_matricula (estudiante_id, asignatura_id, estado)
VALUES (1, 1, 'CONFIRMADA');
UPDATE asignaturas
SET cupos_disponibles = cupos_disponibles - 1
WHERE asignatura_id = 1 AND cupos_disponibles > 0;
COMMIT;

SELECT * FROM registros_matricula WHERE estudiante_id = 1 AND asignatura_id = 1;
SELECT nombre_materia, cupos_disponibles FROM asignaturas WHERE asignatura_id = 1;

/* Transacción B: el INSERT queda deshecho por ROLLBACK. */
BEGIN;
INSERT INTO registros_matricula (estudiante_id, asignatura_id, estado)
VALUES (2, 1, 'PENDIENTE');
-- Simulación de fallo: se omite deliberadamente el UPDATE de cupos.
ROLLBACK;

SELECT * FROM registros_matricula WHERE estudiante_id = 2 AND asignatura_id = 1;
SELECT nombre_materia, cupos_disponibles FROM asignaturas WHERE asignatura_id = 1;

/* Transacción C: la excepción se informa y luego se deshace toda la unidad. */
BEGIN;
UPDATE asignaturas SET cupos_disponibles = cupos_disponibles - 1
WHERE asignatura_id = 1 AND cupos_disponibles > 0;
UPDATE asignaturas SET cupos_disponibles = cupos_disponibles - 1
WHERE asignatura_id = 2 AND cupos_disponibles > 0;
DO $$
BEGIN
    UPDATE asignaturas SET cupos_disponibles = cupos_disponibles - 1
    WHERE asignatura_id = 999 AND cupos_disponibles > 0;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La asignatura 999 no existe: se cancela la transacción';
    END IF;
EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'Error controlado: %', SQLERRM;
END $$;
ROLLBACK;

-- Verificación posterior: los cupos 1 y 2 deben conservar sus valores previos.

/* Consulta de control final, después de hacer ROLLBACK de la transacción C. */
SELECT asignatura_id, nombre_materia, cupos_disponibles
FROM asignaturas ORDER BY asignatura_id;

/*
   Patrón recomendado para una matrícula concurrente.
   El UPDATE condicional adquiere un bloqueo de fila y evita cupos negativos.
   Si ROW_COUNT = 0, la aplicación debe hacer ROLLBACK y mostrar "sin cupos".
*/
BEGIN;
UPDATE asignaturas
SET cupos_disponibles = cupos_disponibles - 1
WHERE asignatura_id = 3 AND cupos_disponibles > 0;
-- Solo si el UPDATE afectó una fila se debe insertar la matrícula y confirmar.
ROLLBACK;

